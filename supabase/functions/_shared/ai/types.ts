// VIBRA AI (docs/vibra-ai.md): provider-neutral types. Nothing outside the
// vibra-ai function imports these, so the app never depends on a provider.

/** Where a verified item came from. */
export type Source = "spotify" | "vibra_events" | "vibra_communities" | "musical_dna" | "genre_catalog";

/** A fact a tool returned during this request: the only things that may be shown as verified. */
export type VerifiedItem = {
  ref: string;
  kind: "artist" | "album" | "track" | "event" | "community" | "genre";
  title: string;
  subtitle: string | null;
  url: string | null;
  image_url: string | null;
  date: string | null;
  source: Source;
  /** Generated by the assistant: why it is relevant. Never a fact. */
  note?: string | null;
};

/** A generated idea that is not backed by data (shown as such). */
export type Idea = { title: string; kind: "genre" | "listening_tip" | "other"; note: string };

export type AssistantAnswer = {
  /** Generated prose. Always labelled as AI-generated in the app. */
  answer: string;
  verified: VerifiedItem[];
  ideas: Idea[];
  /** Items the model cited that no tool had returned (dropped). */
  dropped: number;
  /** "ok", or why there is no full answer. */
  status: "ok" | "refused" | "incomplete";
};

export type ChatTurn = { role: "user" | "assistant"; content: string };

export type MyProfile = {
  families: { key: string; percent: number }[];
  subgenres: { key: string; percent: number }[];
  top_artists: string[];
  picked_genres: string[];
  has_data: boolean;
};

export type EventRow = {
  id: string;
  name: string;
  artist_name: string | null;
  venue_name: string | null;
  city: string | null;
  country: string | null;
  event_date: string;
  ticket_url: string | null;
  image_url: string | null;
  genres: string[] | null;
};

export type CommunityRow = {
  id: string;
  name: string;
  description: string;
  kind: string;
  genre_key: string | null;
  genre_family: string | null;
  artist_name: string | null;
  member_count: number;
  my_role: string | null;
};

/**
 * What the tools may read. Implemented with the caller's own Supabase
 * session (RLS applies) and Spotify's app credentials: never a user's
 * Spotify token.
 */
export interface AssistantData {
  myProfile(): Promise<MyProfile>;
  // deno-lint-ignore no-explicit-any
  spotify(path: string): Promise<{ unavailable: true } | { data: any }>;
  upcomingEvents(filter: { artist: string | null; city: string | null }): Promise<EventRow[]>;
  communities(): Promise<CommunityRow[]>;
}

/** A provider answers one question; tools and the answer check are shared. */
export interface AssistantProvider {
  readonly name: string;
  ask(history: ChatTurn[], data: AssistantData): Promise<AssistantAnswer>;
}
