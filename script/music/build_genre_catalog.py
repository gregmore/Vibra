#!/usr/bin/env python3
"""Generates the TypeScript and Dart genre catalogues from one JSON source.

Source of truth: supabase/functions/_shared/genre_catalog.json
Outputs:        supabase/functions/_shared/genre_catalog.ts
                lib/core/music/genre_catalog.g.dart
Run after editing the JSON:  python3 -I script/music/build_genre_catalog.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "supabase/functions/_shared/genre_catalog.json"
TS_OUT = ROOT / "supabase/functions/_shared/genre_catalog.ts"
DART_OUT = ROOT / "lib/core/music/genre_catalog.g.dart"


def dart_str(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def main() -> None:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    TS_OUT.write_text(
        "// GENERATED by script/music/build_genre_catalog.py from genre_catalog.json.\n"
        "// Do not edit by hand.\n"
        f"export const GENRE_CATALOG = {json.dumps(data, ensure_ascii=False)} as const;\n",
        encoding="utf-8",
    )
    lines = [
        "// GENERATED by script/music/build_genre_catalog.py from",
        "// supabase/functions/_shared/genre_catalog.json. Do not edit by hand.",
        "",
        "part of 'genre_catalog.dart';",
        "",
        f"const int _catalogVersion = {data['version']};",
        "",
        "const List<GenreFamilyInfo> _families = [",
    ]
    for family in data["families"]:
        lines.append(f"  GenreFamilyInfo(key: {dart_str(family['key'])}, label: {dart_str(family['label'])}),")
    lines += ["];", "", "const List<SubgenreInfo> _subgenres = ["]
    for sub in data["subgenres"]:
        lines.append(
            f"  SubgenreInfo(key: {dart_str(sub['key'])}, family: {dart_str(sub['family'])}, "
            f"label: {dart_str(sub['label'])}),"
        )
    lines += ["];", ""]
    DART_OUT.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
